"""Tracks each callout's anchor through the footage so its dotted line stays on the part.

Reads CALLOUTS from edit.js (via node) and follows the points picked on its key frames
with pyramidal Lucas-Kanade optical flow: backwards from the first key, forwards from the
last, and between two keys from both ends, blended so the path meets each key. Writes tracks.js:
window.TRACKS = { <id>: { f0: first frame index, xy: [x0, y0, x1, y1, ...] } } in source pixels.

usage: python3 track.py            (run after prepare.sh)
"""
import json
import os
import subprocess

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FPS = 30
SCALE = 0.5                      # track on half-size frames: faster and less noisy

callouts = json.loads(subprocess.check_output(
    ['node', '-e', "const fs=require('fs'),vm=require('vm');const c={window:{}};"
     "vm.runInNewContext(fs.readFileSync(process.argv[1],'utf8'),c);"
     "console.log(JSON.stringify(c.window.EDIT.CALLOUTS))", os.path.join(HERE, 'edit.js')]))


def gray(i):
    im = cv2.imread(os.path.join(HERE, 'assets', 'frames', f'{i:05d}.jpg'), cv2.IMREAD_GRAYSCALE)
    return cv2.resize(im, None, fx=SCALE, fy=SCALE, interpolation=cv2.INTER_AREA)


LK = dict(winSize=(31, 31), maxLevel=4, criteria=(cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 30, 0.01))


def follow(start, stop, step, anchor):
    """Track from frame `start` to `stop` (inclusive) one frame at a time; returns {frame: (x, y)}."""
    prev = gray(start)
    a = np.array(anchor, np.float32) * SCALE
    # trackable corners near the anchor, plus the anchor itself
    mask = np.zeros_like(prev)
    cv2.circle(mask, (int(a[0]), int(a[1])), 40, 255, -1)
    pts = cv2.goodFeaturesToTrack(prev, 40, 0.01, 4, mask=mask)
    pts = np.vstack([a.reshape(1, 1, 2), pts]) if pts is not None else a.reshape(1, 1, 2)
    out = {start: tuple(anchor)}
    for i in range(start + step, stop + step, step):
        cur = gray(i)
        nxt, st, _ = cv2.calcOpticalFlowPyrLK(prev, cur, pts, None, **LK)
        back, st2, _ = cv2.calcOpticalFlowPyrLK(cur, prev, nxt, None, **LK)
        ok = (st.ravel() == 1) & (st2.ravel() == 1) & (np.linalg.norm(back - pts, axis=2).ravel() < 1.0)
        if ok.sum() >= 3:
            # the anchor moves by the median motion of the points that tracked cleanly
            d = np.median((nxt - pts)[ok], axis=0).ravel()
            a = a + d
            pts = nxt[ok].reshape(-1, 1, 2)
        if len(pts) < 8:          # refill corners around the current anchor when too many are lost
            mask = np.zeros_like(cur)
            cv2.circle(mask, (int(a[0]), int(a[1])), 40, 255, -1)
            more = cv2.goodFeaturesToTrack(cur, 40, 0.01, 4, mask=mask)
            if more is not None:
                pts = np.vstack([pts, more]).astype(np.float32)
        out[i] = (float(a[0] / SCALE), float(a[1] / SCALE))
        prev = cur
    return out


def frame(t):
    return round(t * FPS) + 1


tracks = {}
for c in callouts:
    f0, f1 = frame(c['t0']), frame(c['t1'])
    keys = [(frame(t), (x, y)) for t, x, y in c['keys']]
    path = {**follow(keys[0][0], f0, -1, keys[0][1]), **follow(keys[-1][0], f1, 1, keys[-1][1])}
    for (fa, pa), (fb, pb) in zip(keys, keys[1:]):
        fwd, bwd = follow(fa, fb, 1, pa), follow(fb, fa, -1, pb)
        for i in range(fa, fb + 1):
            w = (i - fa) / (fb - fa)
            path[i] = tuple((1 - w) * np.array(fwd[i]) + w * np.array(bwd[i]))
    xy = [round(v, 1) for i in range(f0, f1 + 1) for v in path[i]]
    tracks[c['id']] = {'f0': f0, 'xy': xy}
    print(c['id'], f'frames {f0}-{f1}', 'drift', np.round(np.subtract(path[f1], path[f0]), 1))

with open(os.path.join(HERE, 'tracks.js'), 'w') as f:
    f.write('// generated by track.py: callout anchors per frame, in source pixels\n')
    f.write('window.TRACKS = ' + json.dumps(tracks, separators=(',', ':')) + ';\n')
print('wrote tracks.js')
